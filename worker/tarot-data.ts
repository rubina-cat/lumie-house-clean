function buildMinor(): TarotCard[] {
  const out: TarotCard[] = [];
  for (const s of SUITS) {
    for (let i = 0; i < 14; i++) {
      const isCourt = i >= 10;
      const court = isCourt ? COURT[i - 10] : null;
      out.push({
        id: `${s.key}${i + 1}`,
        name: court ? `${s.zh}${court.zh}` : `${s.zh}${RANKS[i]}`,
        en: court ? `${court.en} of ${s.en}` : `${RANK_EN[i]} of ${s.en}`,
        arcana: s.key,
        num: court ? court.zh : String(i + 1),
        glyph: s.glyph,
        up: s.up[i],
        rev: s.rev[i],
      });
    }
  }
  return out;
}

